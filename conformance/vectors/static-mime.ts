#!/usr/bin/env bun
/**
 * The static file server's content types and `content-disposition` rule,
 * taken from the Bun runtime frozen TS runs on, never from a hand-copied table.
 *
 *   bun conformance/vectors/static-mime.ts          # rewrite the data file
 *   bun conformance/vectors/static-mime.ts --check  # exit 1 on any drift
 *
 * `app.ts` answers a file with `content-type: file.type` (or `text/html` for a
 * real path ending `.html`), and Bun adds `content-disposition:
 * filename="<basename>"` for some of those types. Both are asked of the real
 * runtime here: `Bun.file(path).type` for every extension Bun knows
 * (`bun-mime-extensions.txt`, from the pinned Bun source), and a live
 * `Bun.serve` answering the same shape of response `app.ts` does, per type.
 *
 * Self-checks: every listed extension resolves case-insensitively, and every
 * extension in `/etc/mime.types` that the list lacks resolves to the
 * runtime's unknown type, so a list missing something the runtime knows fails
 * here rather than in a review.
 */
import { strict as assert } from "node:assert";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const repo = resolve(import.meta.dir, "../..");
const target = resolve(repo, "crates/omni-gateway/data/static-mime.tsv");
const exts = readFileSync(resolve(import.meta.dir, "bun-mime-extensions.txt"), "utf8")
  .split("\n")
  .filter((l) => l.length > 0 && !l.startsWith("#"));
assert.equal(new Set(exts).size, exts.length, "duplicate extension");

const typeOf = (name: string) => Bun.file(`/nonexistent-omni/${name}`).type;
const unknown = typeOf("noext");
assert.equal(typeOf("x.definitely-not-a-type"), unknown);

const byExt = new Map<string, string>();
for (const ext of exts) {
  const t = typeOf(`f.${ext}`);
  assert.equal(typeOf(`f.${ext.toUpperCase()}`), t, `case-insensitive ${ext}`);
  byExt.set(ext, t);
}

// Completeness against an independent extension list.
if (existsSync("/etc/mime.types")) {
  const listed = new Set(exts);
  for (const line of readFileSync("/etc/mime.types", "utf8").split("\n")) {
    if (line.startsWith("#")) continue;
    for (const entry of line.split(/\s+/).slice(1)) {
      // The runtime keys on the text after the last dot (`cwl.json` is `json`).
      const ext = entry.slice(entry.lastIndexOf(".") + 1);
      if (ext.length === 0 || listed.has(ext.toLowerCase())) continue;
      assert.equal(typeOf(`f.${ext}`), unknown, `runtime knows unlisted .${ext}`);
    }
  }
}

// Disposition per type, asked of a live server answering as `app.ts` does.
const dir = mkdtempSync("/tmp/opencode/static-mime-");
const probe = join(dir, "probe.bin");
writeFileSync(probe, "x");
const server = Bun.serve({
  port: 0,
  hostname: "127.0.0.1",
  fetch(req) {
    const type = new URL(req.url).searchParams.get("t") as string;
    return new Response(Bun.file(probe), {
      headers: { "cache-control": "no-cache", "content-type": type },
    });
  },
});
const types = [...new Set([...byExt.values(), unknown, "text/html"])].sort();
const disposition = new Map<string, boolean>();
for (const t of types) {
  const res = await fetch(`http://127.0.0.1:${server.port}/?t=${encodeURIComponent(t)}`);
  await res.arrayBuffer();
  assert.equal(res.headers.get("content-type"), t);
  const d = res.headers.get("content-disposition");
  if (d !== null) assert.equal(d, 'filename="probe.bin"');
  disposition.set(t, d !== null);
}
server.stop(true);
rmSync(dir, { recursive: true, force: true });

const lines = [
  "# Generated by conformance/vectors/static-mime.ts from the Bun runtime frozen TS runs on.",
  `# bun ${Bun.version}; do not edit by hand.`,
  `unknown\t${unknown}`,
  ...types.map((t) => `type\t${t}\t${disposition.get(t) ? 1 : 0}`),
  ...[...byExt.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([e, t]) => `ext\t${e}\t${t}`),
];
const text = `${lines.join("\n")}\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== text) {
    console.error(`drift: ${target} differs from the runtime`);
    process.exit(1);
  }
  console.log(`static-mime: ${byExt.size} extensions, ${types.length} types, no drift`);
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target}: ${byExt.size} extensions, ${types.length} types`);
}
